local regex = require("codediff.review.regex")

local function m(p)
  local f, err = regex.compile(p)
  assert(f, err)
  return f
end

describe("review.regex", function()
  it("matches anchored prefix", function()
    local f = m("^server/")
    assert.is_true(f("server/a.go"))
    assert.is_false(f("web/server/a.go"))
  end)

  it("matches escaped dot and end anchor", function()
    local f = m("\\.go$")
    assert.is_true(f("a/b.go"))
    assert.is_false(f("a/bxgo"))
    assert.is_false(f("a/b.go.txt"))
  end)

  it("handles alternation in a group", function()
    local f = m("\\.(lock|sum)$")
    assert.is_true(f("go.sum"))
    assert.is_true(f("yarn.lock"))
    assert.is_false(f("lockfile.txt"))
  end)

  it("matches package-lock", function()
    local f = m("package-lock\\.json$")
    assert.is_true(f("web/package-lock.json"))
    assert.is_false(f("web/package-lock.jsonx"))
  end)

  it("treats very-magic specials as literals", function()
    assert.is_true(m("<")("a<b"))
    assert.is_false(m("<")("ab"))
    assert.is_true(m("@")("a@b"))
    assert.is_true(m("a=b")("xa=b"))
    assert.is_false(m("a=b")("xab"))
    assert.is_true(m("%")("100%"))
    assert.is_true(m("~")("a~"))
    assert.is_true(m("a&b")("a&b"))
    assert.is_true(m(">")("a>"))
    assert.is_true(m("x@3")("x@3"))
  end)

  it("handles quantifiers and braces", function()
    assert.is_true(m("^a{2,3}$")("aaa"))
    assert.is_false(m("^a{2,3}$")("aaaa"))
    assert.is_true(m("^a{2}$")("aa"))
    assert.is_true(m("^a{2,}$")("aaaa"))
    assert.is_true(m("a+b*c?")("a"))
    assert.is_true(m("a{")("a{"))
    assert.is_true(m("{x}")("{x}"))
    assert.is_false(m("{x}")("x"))
  end)

  it("drops lazy modifier instead of making it optional", function()
    local f = m("^a+?$")
    assert.is_true(f("aa"))
    assert.is_false(f(""))
  end)

  it("is case sensitive regardless of ignorecase", function()
    local old = vim.o.ignorecase
    vim.o.ignorecase = true
    local f = m("^Foo")
    assert.is_false(f("foo"))
    assert.is_true(f("Foo"))
    vim.o.ignorecase = old
  end)

  it("handles character classes", function()
    local f = m("^[a-c]+[<>=]\\d$")
    assert.is_true(f("ab<1"))
    assert.is_false(f("ad<1"))
    assert.is_true(m("[\\d]+")("x5"))
    assert.is_false(m("^[\\d]$")("d"))
    assert.is_true(m("^[^/]+$")("abc"))
    assert.is_false(m("^[^/]+$")("a/c"))
    assert.is_true(m("^[\\]x]$")("]"))
    assert.is_true(m("^[a\\-z]$")("-"))
    assert.is_true(m("^[.]$")("."))
    assert.is_false(m("^[.]$")("a"))
    assert.is_true(m("^[\\w.-]+$")("a-b.c_d"))
  end)

  it("handles dot, \\w, \\s", function()
    assert.is_true(m("^a.c$")("abc"))
    assert.is_true(m("^\\w+\\s\\w+$")("ab cd"))
  end)

  it("handles escaped punctuation", function()
    assert.is_true(m("a\\/b")("a/b"))
    assert.is_true(m("\\(x\\)")("(x)"))
    assert.is_true(m("\\<")("<"))
    assert.is_true(m("a\\+")("a+"))
  end)

  it("handles more than nine groups", function()
    local f = m("^(a)(b)(c)(d)(e)(f)(g)(h)(i)(j)(k)$")
    assert.is_true(f("abcdefghijk"))
  end)

  it("supports non-capturing, named groups and lookarounds", function()
    assert.is_true(m("^(?:ab)+$")("abab"))
    assert.is_true(m("^(?<dir>src|lib)/")("lib/x"))
    local f = m("^scripts/(?!pre-pr/)")
    assert.is_true(f("scripts/deploy.sh"))
    assert.is_false(f("scripts/pre-pr/check.sh"))
    local la = m("^a(?=b)")
    assert.is_true(la("abc"))
    assert.is_false(la("ac"))
    local lb = m("(?<=src/)main")
    assert.is_true(lb("src/main.go"))
    assert.is_false(lb("lib/main.go"))
    local nlb = m("(?<!_)test\\.go$")
    assert.is_true(nlb("test.go"))
    assert.is_false(nlb("a_test.go"))
    assert.is_true(m("^(?:a(?!x)|b)c$")("ac"))
  end)

  it("rejects unsupported constructs", function()
    for _, p in ipairs({ "(?i)a", "(?<1n>a)", "(?=a)*", "\\bfoo", "foo\\B", "(a)\\1", "\\x41", "[]", "(unclosed", "a)", "[abc", "*a", "a**", "a|*b" }) do
      local f, err = regex.compile(p)
      assert.is_nil(f, p)
      assert.is_string(err, p)
    end
  end)

  it("gives clear messages", function()
    assert.matches("%(%?i", select(2, regex.compile("(?i)a")))
    assert.matches("boundary", select(2, regex.compile("\\bx")))
    assert.matches("backreference", select(2, regex.compile("(a)\\1")))
  end)
end)
